	public static Texture2D ColorBitmap(string name, Color main)
	{
		string key = name + main.ToHtml();
		if (Cache.TryGetValue(key, out var saved))
		{
			return saved;
		}
		if (!Rows.TryGetValue(name, out var rows))
		{
			return null;
		}
		Image image = Image.CreateEmpty(rows[0].Length, rows.Length, useMipmaps: false, Image.Format.Rgba8);
		for (int y = 0; y < rows.Length; y++)
		{
			for (int x = 0; x < rows[y].Length; x++)
			{
				image.SetPixel(x, y, rows[y][x] switch
				{
					'w' => Colors.White, 
					'-' => main.Lerp(Colors.Black, 0.45f), 
					'+' => main.Lerp(Colors.White, 0.45f), 
					'#' => main, 
					_ => Colors.Transparent, 
				});
			}
		}
		return Cache[key] = ImageTexture.CreateFromImage(image);
	}

	public static Texture2D Mono(string name)
	{
		if (Cache.TryGetValue(name, out var texture))
		{
			return texture;
		}
		if (!Rows.TryGetValue(name, out var rows))
		{
			return null;
		}
		bool fill = rows.Any((string r) => r.Contains('#') || r.Contains('+'));
		Image image = Image.CreateEmpty(rows[0].Length, rows.Length, useMipmaps: false, Image.Format.Rgba8);
		for (int y = 0; y < rows.Length; y++)
		{
			for (int x = 0; x < rows[y].Length; x++)
			{
				char c = rows[y][x];
				image.SetPixel(x, y, (c == '#' || c == '+' || (!fill && c == '-')) ? Colors.White : Colors.Transparent);
			}
		}
		return Cache[name] = ImageTexture.CreateFromImage(image);
	}
