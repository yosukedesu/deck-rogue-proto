// src/ui/vocab.ts — ブラウザ版 (プロト) の伏せ用語 (2026-09-12 ユーザー「ブラウザ版の戦場はからくり表記わかりにくいので罠とか伏せでいい」)。
// 世界の言葉「からくり」は Unity (絵本の肌) だけが使う。プロトは検証用なので分かりやすさ優先 = データ由来の説明文 (レリック・敵のフレーバー・
// デッキ/リーダーの説明) もこの表で「伏せ」の語に写してから描く。engine の内部名 (SetCard・setSlots…) は不変。順序は長い語から
const RULES: readonly [string, string][] = [
  ['からくり壊し', '伏せ破壊'],
  ['からくりを動かす', '発動する'],
  ['からくりから取り出す', '回収する'],
  ['巻いたままにする', '温存する'],
  ['巻いたまま', '温存'],
  ['取り出した', '回収した'],
  ['取り出す', '回収'],
  ['仕込み札', '伏せ札'],
  ['仕込み枠', '伏せ枠'],
  ['仕込んだ', '伏せた'],
  ['仕込める', '伏せられる'],
  ['仕込めない', '伏せられない'],
  ['仕込む', '伏せる'],
  ['仕込み', '伏せ'],
  ['からくりあり', '伏せ札あり'],
  ['からくりなし', '伏せ札なし'],
  ['からくりがある間', '伏せ札がある間'],
  ['からくりが無い', '伏せ札が無い'],
  ['からくりへの反応', '伏せへの反応'],
  ['からくり警戒', '伏せ警戒'],
  ['からくり中', '伏せ中'],
  ['からくりの確認', '発動確認'],
  ['からくり', '伏せ場'],
  ['動かすには', '発動するには'],
  ['動かすと', '発動すると'],
  ['動かす時', '発動時'],
  ['動かす候補', '発動候補'],
  ['動かす', '発動'],
]

/** データ由来の説明文をブラウザ版の伏せ用語へ写す (純関数) */
export function webVocab(text: string): string {
  let s = text
  for (const [from, to] of RULES) s = s.split(from).join(to)
  return s
}
